"""Derive the Bailey & Love ligature repair table from the other two books.

The 28th edition PDF maps its ff/fi/fl ligature glyphs to a bare "f", so the extracted text
reads "fstula" for fistula, "fnac" for FNAC and "frst" for first. That is not something
Unicode normalisation can fix: the second letter never reaches the text layer at all.

The first attempt at this was a hand-written list of about 80 words, which left more than six
thousand occurrences unrepaired, including "fstula" 241 times. Worse, it was verified against
itself: checking the repaired text for the words that had just been repaired of course found
none left.

So this derives the table from evidence instead. S Das and SRB do not have the fault, so
between them they supply a vocabulary of words known to be real. A Bailey word qualifies for
repair only when all of these hold:

  - it is not already a known word (so "fat", "often" and "left" are never touched);
  - restoring one "f" to "ff", "fi" or "fl" produces a known word;
  - exactly one such restoration does, so there is nothing to guess between.

Run it after re-extracting the sources, and commit the result:

    python derive_ligatures.py

Some entries are word fragments ("infam" -> "inflam") left by hyphenation across a line
break. Repairing those is still right: the letter really is missing.
"""

import collections
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
WORD = re.compile(r"[a-z]{3,}")

# books without the fault, used as the vocabulary
CLEAN = ("sdas", "srb")
BROKEN = "bailey"

# a word must appear at least this often in the clean books to count as real, so that one
# OCR artefact over there cannot license a wrong "repair" over here
MIN_SEEN = 2


def vocabulary(folders) -> collections.Counter:
    seen = collections.Counter()
    for folder in folders:
        for path in (HERE / "sources" / folder).glob("*.txt"):
            seen.update(WORD.findall(path.read_text(encoding="utf-8", errors="replace").lower()))
    return seen


def derive():
    clean = vocabulary(CLEAN)
    known = {w for w, n in clean.items() if n >= MIN_SEEN}
    broken = vocabulary([BROKEN])

    repairs, ambiguous = {}, []
    for word, count in broken.items():
        if word in known or "f" not in word:
            continue
        candidates = set()
        for i, ch in enumerate(word):
            if ch != "f":
                continue
            for restored in ("f", "i", "l"):
                candidate = word[:i + 1] + restored + word[i + 1:]
                if candidate in known:
                    candidates.add(candidate)
        if len(candidates) == 1:
            repairs[word] = candidates.pop()
        elif candidates:
            ambiguous.append((word, sorted(candidates), count))
    return repairs, ambiguous, broken


def main() -> int:
    repairs, ambiguous, broken = derive()
    occurrences = sum(broken[w] for w in repairs)

    out = HERE / "ligature_repairs.py"
    out.write_text(
        '"""Generated by derive_ligatures.py. Do not edit by hand.\n\n'
        f"{len(repairs)} word types, {occurrences} occurrences in the extracted Bailey & Love\n"
        'text. See derive_ligatures.py for how these are established.\n"""\n\n'
        "LIGATURE_REPAIRS = {\n"
        + "".join(f'    "{w}": "{r}",\n' for w, r in sorted(repairs.items()))
        + "}\n",
        encoding="utf-8",
    )

    print(f"  repairs derived : {len(repairs)} word types, {occurrences:,} occurrences")
    print(f"  ambiguous       : {len(ambiguous)} (left alone)")
    for word, cands, n in sorted(ambiguous, key=lambda x: -x[2])[:10]:
        print(f"    {word} -> {cands} ({n})")
    print(f"  written         : {out.relative_to(HERE)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
